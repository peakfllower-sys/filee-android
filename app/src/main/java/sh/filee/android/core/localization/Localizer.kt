    fun get(key: String, lang: String = "zh-CN", vararg args: Any): String {
        val dict = dictionaries[lang] ?: dictionaries["zh-CN"]!!
        val raw = dict[key] ?: dictionaries["en"]?.get(key) ?: key
        var result = raw
        args.forEachIndexed { index, arg ->
            result = result.replace("{$index}", arg.toString())
        }
        return result
    }

    fun presetName(preset: Preset, lang: String): String {
        if (preset.name.isNotBlank()) return preset.name
        val key = preset.nameKey ?: return preset.targetFormat.uppercase()
        return get(key, lang)
    }

    fun profileName(profile: ToolbarProfile, lang: String): String {
        if (profile.name.isNotBlank()) return profile.name
        val key = profile.nameKey ?: return profile.id
        return get(key, lang)
    }

